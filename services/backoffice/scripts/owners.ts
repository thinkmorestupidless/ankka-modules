// Makes the typed clients the page calls, one file per owning service, from the route table
// (src/server/routes.ts). They go to src/shared/owners/ so the page imports them without the server:
// each file imports nothing. `npm run owners` writes them; `node scripts/owners.ts <dir>` writes them
// elsewhere (the unit test compares the two).
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { table, type Row } from "../src/server/routes.ts";

const Header = "// Generated by scripts/owners.ts from src/server/routes.ts; do not edit. Run `npm run owners`.\n";

const pascal = (s: string) => s.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
const camel = (s: string) => { const p = pascal(s); return p[0]!.toLowerCase() + p.slice(1); };
const params = (p: string) => [...p.matchAll(/\{(\w+)\}/g)].map((m) => m[1]!);

/** The method and the path's literal segments; a path ending in a parameter adds `By<Param>`. */
export function nameOf(row: Row): string {
  const segments = row.path.split("/").filter(Boolean);
  const literals = segments.filter((s) => !s.startsWith("{")).map(pascal).join("");
  const last = segments.at(-1);
  const by = last?.startsWith("{") ? `By${pascal(last.slice(1, -1))}` : "";
  return `${row.method.toLowerCase()}${literals}${by}`;
}

function client(row: Row): string {
  const names = params(row.path);
  const url = row.path.replace(/\{(\w+)\}/g, (_, n: string) => `\${encodeURIComponent(params.${n})}`);
  const args = names.length ? `params: { ${names.map((n) => `${n}: string`).join("; ")} }, options: Options = {}` : "options: Options = {}";
  return [
    `/** ${row.method} ${row.path}: ${row.permission} */`,
    `export function ${nameOf(row)}(${args}): Promise<Response> {`,
    `  return call("${row.method}", \`/api/s/${row.service}${url}\`, options);`,
    `}`,
  ].join("\n");
}

const Call = `export interface Options {
  query?: Record<string, string>;
  body?: unknown;
}

function call(method: string, path: string, options: Options): Promise<Response> {
  const query = options.query && Object.keys(options.query).length ? \`?\${new URLSearchParams(options.query)}\` : "";
  const headers: Record<string, string> = {};
  if (method !== "GET") headers["X-Backoffice"] = "1";
  if (options.body !== undefined) headers["Content-Type"] = "application/json";
  return fetch(path + query, {
    method,
    headers,
    body: options.body === undefined ? undefined : JSON.stringify(options.body),
  });
}`;

/** Each generated file's name and text. */
export function render(rows: readonly Row[] = table): Map<string, string> {
  const services = [...new Set(rows.map((r) => r.service))];
  const files = new Map<string, string>();
  for (const service of services) {
    const own = rows.filter((r) => r.service === service);
    const seen = new Set<string>();
    for (const row of own) {
      const n = nameOf(row);
      if (seen.has(n)) throw new Error(`two routes of ${service} are named ${n}: rename a path`);
      seen.add(n);
    }
    files.set(`${service}.ts`, `${Header}// ${service}: ${own.length} routes.\n\n${Call}\n\n${own.map(client).join("\n\n")}\n`);
  }
  const index = services.map((s) => `export * as ${camel(s)} from "./${s}.ts";`).join("\n");
  files.set("index.ts", `${Header}\n${index}\n`);
  return files;
}

export function write(dir: string, rows: readonly Row[] = table): void {
  mkdirSync(dir, { recursive: true });
  for (const [name, text] of render(rows)) writeFileSync(path.join(dir, name), text);
}

const here = path.dirname(fileURLToPath(import.meta.url));
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  write(process.argv[2] ?? path.join(here, "../src/shared/owners"));
}
