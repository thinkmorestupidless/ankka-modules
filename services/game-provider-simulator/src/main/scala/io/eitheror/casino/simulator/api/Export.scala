package io.eitheror.casino.simulator.api

import com.fasterxml.jackson.databind.ObjectMapper
import com.fasterxml.jackson.databind.node.{ArrayNode, ObjectNode}
import io.eitheror.casino.simulator.core.{Callback, RunCallbackRow}

import java.time.Instant
import scala.util.Try

/**
 * A run as a recording (FR-021; contracts/run-export.md), in the shape spec 001's recording
 * contract defines, so the brand's parity kit replays it with `contract.port.Recording`. One step
 * per answered attempt, in the order sent; an attempt with no answer is not a step, since a
 * recording replays what was answered.
 */
object Export:

  private val mapper = ObjectMapper()

  def recording(brand: String, runId: String, scenario: String, source: String, version: String, rows: Vector[RunCallbackRow]): ObjectNode =
    val root = mapper.createObjectNode()
    root.put("scenario", s"sim-$scenario-$runId")
    root.put("requirement", s"020/$scenario")
    val first = rows.flatMap(_.attemptsDetail).map(_.sentAt).minOption.getOrElse(0L)
    root.put("recorded_at", Instant.ofEpochMilli(first).toString)
    val original = root.putObject("original")
    original.put("simulator", version)
    original.put("brand", brand)
    original.put("source", source)
    root.put("runs", 1)
    val steps = root.putArray("steps")
    val vary  = root.putObject("vary")
    val answered = rows.flatMap(row => row.attemptsDetail.filter(_.httpStatus.isDefined).map(row -> _)).sortBy((_, a) => (a.sentAt, a.attempt))
    var walletToken = Option.empty[String]
    answered.zipWithIndex.foreach { case ((row, attempt), i) =>
      val step = steps.addObject()
      step.put("name", row.step.fold(s"${row.kind}#${attempt.attempt}")(s => s"$s/${row.kind}#${attempt.attempt}"))
      val request = step.putObject("request")
      request.put("method", "POST")
      request.put("path", row.route)
      val headers = request.putObject("headers")
      headers.put("Content-Type", "application/json")
      headers.put("x-st8-sign", attempt.signature)
      val sent = walletToken.filter(_.nonEmpty).fold(row.body)(t => row.body.replace(t, "{wallet_token}"))
      val body = Try(mapper.readTree(sent)).toOption.filter(n => n != null && n.isObject)
      body match
        case Some(json) => request.set("body", json): Unit
        case None       => request.put("body", sent): Unit
      val response = step.putObject("response")
      response.put("status", attempt.httpStatus.get)
      Try(mapper.readTree(attempt.answer.getOrElse(""))).toOption.filter(_ != null) match
        case Some(json) => response.set("body", json): Unit
        case None       => response.put("body", attempt.answer.getOrElse("")): Unit
      if row.kind == "check" then
        step.putObject("capture").put("wallet_token", "$.token")
        walletToken = Try(mapper.readTree(attempt.answer.getOrElse("")).get("token").asText()).toOption
      vary.put(s"$$.steps[$i].request.headers.x-st8-sign", "random nonce")
      Vector("transaction_id", "cancel_id", "round").foreach { f =>
        if body.exists(_.has(f)) then vary.put(s"$$.steps[$i].request.body.$f", "generated by the simulator"): Unit
      }
      if row.outcome != Callback.MalformedBody then
        vary.put(s"$$.steps[$i].response.body.balance", "depends on the player's balance at replay"): Unit
    }
    root.putArray("outbound"): ArrayNode
    root
