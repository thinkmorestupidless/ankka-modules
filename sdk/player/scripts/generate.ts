// The module clients' route tables and wire shapes, written from the services' kept descriptions
// (`services/*/openapi.player.json`) and each module's `selection.ts` (spec 031,
// contracts/generation.md). `npm run generate` writes `src/<module>/routes.ts` and `shapes.ts`;
// `npm run generate:check` writes nothing and fails naming each file that differs. It reads those
// files and nothing else: no network, no environment, nothing run.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import type { Audience, Method, ModuleName, Route } from "../src/route.ts";
import type { Selection, SelectionRow } from "../src/selection.ts";

export const modules = ["core", "casino", "engagement", "support"] as const satisfies readonly ModuleName[];

export const Header = "// Generated by scripts/generate.ts from services/*/openapi.player.json. Do not edit.";

export interface Schema {
  readonly [keyword: string]: unknown;
}

interface Parameter {
  readonly name: string;
  readonly in: string;
}

interface Content {
  readonly content?: Readonly<Record<string, { readonly schema?: Schema }>>;
}

interface Operation {
  readonly tags?: readonly string[];
  readonly security?: readonly unknown[];
  readonly parameters?: readonly Parameter[];
  readonly requestBody?: Content;
  readonly responses?: Readonly<Record<string, Content>>;
}

/** A service's kept description: what of an OpenAPI document the generator reads. */
export interface Description {
  readonly paths?: Readonly<Record<string, Readonly<Record<string, Operation>>>>;
  readonly components?: { readonly schemas?: Readonly<Record<string, Schema>> };
}

export type Descriptions = Readonly<Record<string, Description>>;
export type Selections = Readonly<Record<ModuleName, Selection>>;

/** Every rule a selection or a description broke, each as one line. */
export class GenerationError extends Error {
  readonly problems: readonly string[];
  constructor(problems: readonly string[]) {
    super(problems.join("\n"));
    this.problems = problems;
  }
}

export interface Generated {
  /** Each module's table, as `routes.ts` holds it. */
  readonly tables: Readonly<Record<ModuleName, readonly Route[]>>;
  /** Each file's text, by its path under `sdk/player/`. */
  readonly files: Readonly<Record<string, string>>;
}

const kept = (service: string) => `services/${service}/openapi.player.json`;

/** The JSON Schema keywords read (research R10); another fails the generation, naming the schema. */
const Subset = new Set(["$ref", "additionalProperties", "anyOf", "description", "enum", "format", "items", "oneOf", "properties", "required", "type"]);
const Scalars: Readonly<Record<string, string>> = { string: "z.string()", integer: "z.number().int()", number: "z.number()", boolean: "z.boolean()", null: "z.null()" };

const pascal = (name: string) => name.split(/[^A-Za-z0-9]+/).filter(Boolean).map((w) => w[0]!.toUpperCase() + w.slice(1)).join("");
const key = (name: string) => (/^[A-Za-z_$][A-Za-z0-9_$]*$/.test(name) ? name : JSON.stringify(name));
const refName = (schema: Schema) => String(schema.$ref).split("/").pop()!;

/** One module's shapes: what its rows take and answer, and the schemas those refer to. */
class Shapes {
  private readonly descriptions: Descriptions;
  /** A referred schema's parser, by its name in the file (`PlayersTerminal`). */
  private readonly referred = new Map<string, string>();
  private readonly visiting = new Set<string>();
  /** An exported shape, by name: its parser, its comment and the schema it was read from. */
  readonly exported = new Map<string, { expr: string; comment: string; source: string }>();

  constructor(descriptions: Descriptions) {
    this.descriptions = descriptions;
  }

  /** The parser of a schema of `service`, as Zod's source; `where` names it in a failure. */
  expr(service: string, where: string, schema: Schema, indent = ""): string {
    for (const keyword of Object.keys(schema)) {
      if (!Subset.has(keyword)) throw new GenerationError([`${kept(service)}: the schema ${where} uses ${keyword}, outside what the generator reads`]);
    }
    if (schema.$ref !== undefined) return this.refer(service, refName(schema));
    const anyOf = (schema.anyOf ?? schema.oneOf) as readonly Schema[] | undefined;
    if (anyOf) {
      const others = anyOf.filter((s) => s.type !== "null").map((s) => this.expr(service, where, s, indent));
      const one = others.length === 1 ? others[0]! : `z.union([${others.join(", ")}])`;
      return others.length < anyOf.length ? `${one}.nullable()` : one;
    }
    const types = Array.isArray(schema.type) ? (schema.type as string[]) : schema.type === undefined ? [] : [String(schema.type)];
    const nullable = types.length > 1 && types.includes("null");
    const base = types.filter((t) => !nullable || t !== "null");
    if (base.length > 1) throw new GenerationError([`${kept(service)}: the schema ${where} uses a type of several (${base.join(", ")}), outside what the generator reads`]);
    return this.typed(service, where, schema, base[0], indent) + (nullable ? ".nullable()" : "");
  }

  private typed(service: string, where: string, schema: Schema, type: string | undefined, indent: string): string {
    if (Array.isArray(schema.enum)) return `z.enum(${JSON.stringify(schema.enum)})`;
    if (type === undefined) return "z.unknown()";
    if (type === "array") return `z.array(${schema.items ? this.expr(service, where, schema.items as Schema, indent) : "z.unknown()"})`;
    if (type === "object") {
      const properties = schema.properties as Readonly<Record<string, Schema>> | undefined;
      if (!properties) {
        const values = schema.additionalProperties;
        return `z.record(z.string(), ${values && typeof values === "object" ? this.expr(service, where, values as Schema, indent) : "z.unknown()"})`;
      }
      const required = new Set((schema.required as string[] | undefined) ?? []);
      const inner = `${indent}  `;
      const fields = Object.entries(properties).map(([name, s]) => `${inner}${key(name)}: ${this.expr(service, `${where}.${name}`, s, inner)}${required.has(name) ? "" : ".optional()"},`);
      // An object passes the fields it does not name, as the services' codecs do.
      return fields.length ? `z.looseObject({\n${fields.join("\n")}\n${indent}})` : "z.looseObject({})";
    }
    const scalar = Scalars[type];
    if (!scalar) throw new GenerationError([`${kept(service)}: the schema ${where} uses the type ${type}, outside what the generator reads`]);
    return scalar;
  }

  /** A schema another refers to, emitted once under its service's name. */
  private refer(service: string, name: string): string {
    const as = `${pascal(service)}${name}`;
    if (this.referred.has(as)) return as;
    const schema = this.descriptions[service]?.components?.schemas?.[name];
    if (!schema) throw new GenerationError([`${kept(service)}: a schema refers to ${name}, which it does not hold`]);
    if (this.visiting.has(as)) throw new GenerationError([`${kept(service)}: the schema ${name} uses a reference to itself, outside what the generator reads`]);
    this.visiting.add(as);
    const expr = this.expr(service, name, schema);
    this.visiting.delete(as);
    this.referred.set(as, expr);
    return as;
  }

  /** A row's `takes` or `answers`: a reference at the top is written out under the row's own name. */
  shape(service: string, schema: Schema, name: string, comment: string): string | undefined {
    const top = schema.$ref !== undefined ? this.descriptions[service]?.components?.schemas?.[refName(schema)] : schema;
    if (!top) throw new GenerationError([`${kept(service)}: a schema refers to ${refName(schema)}, which it does not hold`]);
    const source = `${service} ${JSON.stringify(schema)}`;
    const before = this.exported.get(name);
    if (before) return before.source === source ? undefined : `two shapes are named ${name}`;
    this.exported.set(name, { expr: this.expr(service, schema.$ref !== undefined ? refName(schema) : name, top), comment, source });
    return undefined;
  }

  /** `shapes.ts`: the referred schemas by name, each after what it refers to, then the rows' shapes in the rows' order. */
  file(module: ModuleName): string {
    if (this.exported.size === 0) return `${Header}\n\n// \`${module}\`'s rows take and answer no JSON shape: a stream's events are parsed by \`events.ts\`.\nexport {};\n`;
    const clash = [...this.exported.keys()].find((name) => this.referred.has(name));
    if (clash) throw new GenerationError([`${module}/selection.ts: the shape ${clash} has the name of a schema its service refers to`]);
    const out = [Header, 'import { z } from "zod";', ""];
    const written = new Set<string>();
    const write = (name: string): void => {
      if (written.has(name)) return;
      written.add(name);
      const expr = this.referred.get(name)!;
      for (const other of [...this.referred.keys()].sort()) if (other !== name && new RegExp(`\\b${other}\\b`).test(expr)) write(other);
      out.push(`const ${name} = ${expr};`, "");
    };
    for (const name of [...this.referred.keys()].sort()) write(name);
    for (const [name, { expr, comment }] of this.exported) out.push(`/** ${comment} */`, `export const ${name} = ${expr};`, `export type ${name} = z.infer<typeof ${name}>;`, "");
    return `${out.join("\n").trimEnd()}\n`;
  }
}

const jsonOf = (content: Content | undefined): Schema | undefined => content?.content?.["application/json"]?.schema;

/** One row of a table from its selection row and the operation it names; its problems, each one line. */
function row(module: ModuleName, sel: SelectionRow, descriptions: Descriptions, shapes: Shapes, problems: string[]): Route | undefined {
  const at = `${module}/selection.ts: ${sel.id}`;
  const space = sel.operation.indexOf(" ");
  const method = sel.operation.slice(0, space);
  const servicePath = sel.operation.slice(space + 1);
  const op = descriptions[sel.service]?.paths?.[servicePath]?.[method.toLowerCase()];
  if (!op) {
    problems.push(`${at} names ${sel.operation} which ${kept(sel.service)} does not hold`);
    return undefined;
  }
  const before = problems.length;
  const has = (where: string) => new Set((op.parameters ?? []).filter((p) => p.in === where).map((p) => p.name));
  const inPath = has("path");
  const inQuery = has("query");
  for (const name of Object.keys(sel.rename ?? {})) if (!inPath.has(name)) problems.push(`${at} renames the path parameter ${name}, which ${sel.operation} does not have`);
  for (const name of Object.keys(sel.fixed ?? {})) if (!inPath.has(name)) problems.push(`${at} fixes the path parameter ${name}, which ${sel.operation} does not have`);
  const fixedQuery = sel.fixedQuery ? [...new URLSearchParams(sel.fixedQuery).keys()] : [];
  for (const name of [...(sel.query ?? []), ...fixedQuery, ...(sel.brandQuery ? ["brand"] : [])]) {
    if (!inQuery.has(name)) problems.push(`${at} names the query parameter ${name}, which ${sel.operation} does not have`);
  }

  const answers = Object.entries(op.responses ?? {}).filter(([status]) => status === "200" || status === "201").map(([, content]) => content);
  const stream = answers.some((a) => a.content?.["text/event-stream"] !== undefined);
  const answer = answers.map(jsonOf).find((s) => s !== undefined);
  const take = jsonOf(op.requestBody);
  const shaped = (schema: Schema, name: string, what: string) => {
    const problem = shapes.shape(sel.service, schema, name, `What \`${sel.id}\` ${what}: ${sel.service}'s ${sel.operation}.`);
    if (problem) problems.push(`${at}: ${problem}`);
  };
  if (sel.answers !== undefined) {
    if (stream) problems.push(`${at} names what it answers (${sel.answers}), and ${sel.operation} answers a stream, which has no shape`);
    else if (!answer) problems.push(`${at} names what it answers (${sel.answers}), and ${sel.operation} has no JSON 200 or 201 answer`);
    else shaped(answer, sel.answers, "answers");
  } else if (!stream) problems.push(`${at} does not name what it answers, and ${sel.operation} is not a stream`);
  if (sel.takes !== undefined) {
    if (!take) problems.push(`${at} names what it takes (${sel.takes}), and ${sel.operation} takes no JSON body`);
    else shaped(take, sel.takes, "takes");
  }
  if (problems.length > before) return undefined;

  const segments = servicePath.split("/").map((segment) => {
    if (segment === "the-brand") return "{brand}";
    const name = /^\{(.+)\}$/.exec(segment)?.[1];
    if (name === undefined) return segment;
    return sel.fixed?.[name] ?? `{${sel.rename?.[name] ?? name}}`;
  });
  const tags = new Set(op.tags ?? []);
  const audience: Audience = tags.has("ticket") ? "ticket" : tags.has("signed-in") ? "player" : op.security !== undefined && op.security.length === 0 ? "public" : "player";
  return {
    module,
    id: sel.id,
    service: sel.service,
    method: method as Method,
    path: segments.join("/") + (sel.fixedQuery ? `?${sel.fixedQuery}` : ""),
    audience,
    ...(stream ? { stream: true } : {}),
    ...(sel.serverOnly ? { serverOnly: true } : {}),
    ...(sel.visitor ? { visitor: true } : {}),
    ...(sel.brandQuery ? { brandQuery: true } : {}),
    ...(sel.query ? { query: [...sel.query] } : {}),
  };
}

function routesFile(module: ModuleName, table: readonly Route[]): string {
  const line = (r: Route) => `  { ${Object.entries(r).map(([k, v]) => `${k}: ${JSON.stringify(v).replaceAll('","', '", "')}`).join(", ")} },`;
  return [
    Header,
    'import type { Routes } from "../route.ts";',
    "",
    `/** \`${module}\`'s route table: one row for each row of \`selection.ts\`, as the services' kept descriptions have it. */`,
    "export const routes = [",
    ...table.map(line),
    "] as const satisfies Routes;",
    "",
  ].join("\n");
}

/** The tables and the files, from the descriptions and the selections alone; every broken rule is thrown at once. */
export function generate(descriptions: Descriptions, selections: Selections): Generated {
  const problems: string[] = [];
  const tables = {} as Record<ModuleName, Route[]>;
  const files: Record<string, string> = {};
  for (const module of modules) {
    const shapes = new Shapes(descriptions);
    const seen = new Map<string, string>();
    tables[module] = [];
    for (const sel of selections[module]) {
      const first = seen.get(sel.id);
      if (first !== undefined) {
        problems.push(`${module}/selection.ts: two rows share the id ${sel.id}: ${first} and ${sel.operation}`);
        continue;
      }
      seen.set(sel.id, sel.operation);
      try {
        const made = row(module, sel, descriptions, shapes, problems);
        if (made) tables[module].push(made);
      } catch (e) {
        if (!(e instanceof GenerationError)) throw e;
        problems.push(...e.problems);
      }
    }
    if (problems.length === 0) {
      files[`src/${module}/routes.ts`] = routesFile(module, tables[module]);
      files[`src/${module}/shapes.ts`] = shapes.file(module);
    }
  }
  if (problems.length > 0) throw new GenerationError(problems);
  return { tables, files };
}

/** The kept descriptions under a `services/` directory, by service. */
export function descriptionsIn(services: string): Descriptions {
  const found: Record<string, Description> = {};
  for (const service of readdirSync(services).sort()) {
    const file = path.join(services, service, "openapi.player.json");
    if (existsSync(file)) found[service] = JSON.parse(readFileSync(file, "utf8")) as Description;
  }
  return found;
}

/** The four selections under an SDK's `src/`. */
export async function selectionsIn(src: string): Promise<Selections> {
  const found = {} as Record<ModuleName, Selection>;
  for (const module of modules) {
    const loaded = (await import(pathToFileURL(path.join(src, module, "selection.ts")).href)) as { selection: Selection };
    found[module] = loaded.selection;
  }
  return found;
}

/**
 * Generates for the SDK at `sdk` from the descriptions under `services`. With `check`, writes
 * nothing and answers 1 with a line for each file that differs; a broken rule answers 1 with its lines.
 */
export async function run(options: { sdk: string; services: string; check: boolean }): Promise<{ code: number; lines: string[] }> {
  let made: Generated;
  try {
    made = generate(descriptionsIn(options.services), await selectionsIn(path.join(options.sdk, "src")));
  } catch (e) {
    if (!(e instanceof GenerationError)) throw e;
    return { code: 1, lines: [...e.problems] };
  }
  const lines: string[] = [];
  for (const [file, text] of Object.entries(made.files)) {
    const at = path.join(options.sdk, file);
    const now = existsSync(at) ? readFileSync(at, "utf8") : undefined;
    if (now === text) continue;
    if (options.check) lines.push(`${file} is out of date: run npm run generate -w sdk/player`);
    else writeFileSync(at, text);
  }
  return { code: lines.length > 0 ? 1 : 0, lines };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const sdk = path.resolve(import.meta.dirname, "..");
  const done = await run({ sdk, services: path.resolve(sdk, "../../services"), check: process.argv.includes("--check") });
  for (const line of done.lines) console.error(line);
  process.exitCode = done.code;
}
