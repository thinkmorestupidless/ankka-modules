// The steps of each behaviour, read from its `…Step` union in the sources, as the README's tables
// (T053). `npm run readme` writes them between the README's markers; tests/unit/readme.test.ts fails
// when the README and the sources differ.
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");

/** Each behaviour: its name in the README, its module, and the file and type its steps are. */
export const behaviours = [
  { name: "session", module: "core", file: "src/core/session.ts", type: "SessionStep" },
  { name: "deposit", module: "core", file: "src/core/deposit.ts", type: "DepositStep" },
  { name: "play", module: "casino", file: "src/casino/play.ts", type: "PlayStep" },
  { name: "inbox", module: "engagement", file: "src/engagement/inbox.ts", type: "InboxStep" },
  { name: "chat", module: "support", file: "src/support/chat.ts", type: "ChatStep" },
] as const;

export interface StepRow {
  readonly kinds: readonly string[];
  readonly allowed: readonly string[];
  readonly fields: readonly string[];
}

/** One union member per line, `| { kind: …; allowed: readonly [...]; field: … }`. */
export function steps(source: string, type: string): StepRow[] {
  const start = source.indexOf(`export type ${type} =`);
  if (start < 0) throw new Error(`no type ${type}`);
  const rows: StepRow[] = [];
  for (const line of source.slice(start).split("\n").slice(1)) {
    const member = /^\s*\|\s*\{(.*)\}\s*;?\s*$/.exec(line);
    if (!member) break;
    const body = member[1]!;
    const kinds = [.../kind:\s*((?:"[^"]+"\s*\|?\s*)+)(?:;|\s*$)/.exec(body)![1]!.matchAll(/"([^"]+)"/g)].map((m) => m[1]!);
    const allowedPart = /allowed:\s*((?:readonly \[[^\]]*\]\s*\|?\s*)+)(?:;|\s*$)/.exec(body)![1]!;
    const allowed = [...new Set([...allowedPart.matchAll(/"([^"]+)"/g)].map((m) => m[1]!))];
    // the other fields: names at the member's top level, after kind and allowed
    const rest = body.replace(/kind:[^;]*;/, "").replace(/allowed:[^;]*;?/, "");
    let depth = 0;
    let top = "";
    for (const ch of rest) {
      if ("{[(<".includes(ch)) depth++;
      if ("}])>".includes(ch)) depth--;
      top += depth === 0 ? ch : " ";
    }
    const fields = [...top.matchAll(/(?:^|;)\s*([A-Za-z]+\??):/g)].map((m) => m[1]!);
    rows.push({ kinds, allowed, fields });
  }
  return rows;
}

const cell = (xs: readonly string[]) => (xs.length ? xs.map((x) => `\`${x}\``).join(", ") : "—");

export function tables(): string {
  const out: string[] = [];
  for (const b of behaviours) {
    const source = readFileSync(path.join(root, b.file), "utf8");
    out.push(`### ${b.name} (\`${b.module}\`, \`${b.type}\`)`, "", "| Step | Actions it allows | Fields |", "|---|---|---|");
    for (const r of steps(source, b.type)) out.push(`| ${cell(r.kinds)} | ${cell(r.allowed)} | ${cell(r.fields)} |`);
    out.push("");
  }
  return out.join("\n").trimEnd();
}

export const Begin = "<!-- steps: generated by `npm run readme` from the sources; do not edit by hand -->";
export const End = "<!-- steps: end -->";

/** The README with its generated section as the sources make it now. */
export function written(readme: string): string {
  const from = readme.indexOf(Begin);
  const to = readme.indexOf(End);
  if (from < 0 || to < from) throw new Error("the README has no generated steps section");
  return `${readme.slice(0, from + Begin.length)}\n\n${tables()}\n\n${readme.slice(to)}`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const file = path.join(root, "README.md");
  writeFileSync(file, written(readFileSync(file, "utf8")));
}
